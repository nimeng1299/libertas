"""Generate the 美容玻璃 (beauty glass) texture and item model.

The block itself is drawn by BeautyGlassRenderer (a 2px frame on every face, hollow at the seams),
so the texture only ever shows up as a 2px bevel band: pixel row/column 0 is the bright outer rim,
row/column 1 the darker inner rim, and the rest is filler.

Requires Pillow. Run from anywhere: python blockbench/generate_beauty_glass.py
"""

from __future__ import annotations

import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "src/main/resources/assets/libertas"
SIDES = ("north", "south", "east", "west", "up", "down")

THICKNESS = 2  # 边框厚度 (像素)

RIM_HIGHLIGHT = (247, 253, 255, 255)
RIM_INNER = (186, 214, 229, 255)
BODY = (206, 232, 242, 255)
GLINT = (232, 251, 255, 255)


def build_texture() -> Image.Image:
    image = Image.new("RGBA", (16, 16), BODY)
    pixels = image.load()
    for y in range(16):
        for x in range(16):
            distance = min(x, y, 15 - x, 15 - y)
            if distance == 0:
                pixels[x, y] = RIM_HIGHLIGHT
            elif distance == 1:
                pixels[x, y] = RIM_INNER
            else:
                # 极轻微的明暗起伏, 免得整块边框看着像纯色塑料
                shift = ((x * 7 + y * 11) % 5) - 2
                pixels[x, y] = (BODY[0] + shift, BODY[1] + shift, BODY[2] + shift, 255)
    # 内侧那一像素上撒几点高光, 像玻璃的折光
    for x, y in ((3, 1), (9, 1), (14, 5), (14, 10), (11, 14), (5, 14), (1, 4), (1, 10)):
        pixels[x, y] = GLINT
    return image


def bar(name: str, start: tuple[int, int, int], end: tuple[int, int, int]) -> dict:
    """A frame beam; UVs are left out so the loader derives them from from/to (see JsonBakedModel)."""
    return {
        "name": name,
        "from": list(start),
        "to": list(end),
        "faces": {side: {"texture": "#0"} for side in SIDES},
    }


def build_model() -> dict:
    t = THICKNESS
    elements = []
    # 4 根竖柱
    for ix, x0 in enumerate((0, 16 - t)):
        for iz, z0 in enumerate((0, 16 - t)):
            elements.append(bar(f"post_{ix}{iz}", (x0, 0, z0), (x0 + t, 16, z0 + t)))
    # 上下各 2 根沿 X 的横梁 (避让竖柱, 免得共面闪烁)
    for iy, y0 in enumerate((0, 16 - t)):
        for iz, z0 in enumerate((0, 16 - t)):
            elements.append(bar(f"rail_x_{iy}{iz}", (t, y0, z0), (16 - t, y0 + t, z0 + t)))
    # 上下各 2 根沿 Z 的横梁
    for ix, x0 in enumerate((0, 16 - t)):
        for iy, y0 in enumerate((0, 16 - t)):
            elements.append(bar(f"rail_z_{ix}{iy}", (x0, y0, t), (x0 + t, y0 + t, 16 - t)))

    return {
        "credit": "Generated by blockbench/generate_beauty_glass.py",
        "ambientocclusion": False,
        "textures": {
            "0": "libertas:blocks/beauty_glass",
            "particle": "libertas:blocks/beauty_glass",
        },
        "elements": elements,
    }


def write_json(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def main() -> None:
    texture_path = ASSETS / "textures/blocks/beauty_glass.png"
    texture_path.parent.mkdir(parents=True, exist_ok=True)
    build_texture().save(texture_path)
    write_json(ASSETS / "models/item/beautyGlass.json", build_model())
    print(f"wrote {texture_path}")
    print(f"wrote {ASSETS / 'models/item/beautyGlass.json'}")


if __name__ == "__main__":
    main()
